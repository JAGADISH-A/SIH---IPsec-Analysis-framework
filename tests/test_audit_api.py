class TestAuditApiRoutes(_StoreTestCase):
    def test_list_route(self):
        payload = _get(self.store, AUDIT_EVENTS_PATH, limit=3)
        self.assertEqual("audit-events", payload["api"])
        self.assertEqual(3, payload["count"])
        self.assertEqual(list(AUDIT_STAGE_ORDER), payload["stage_order"])

    def test_detail_route_returns_the_persisted_record(self):
        event_id = self.events[0].event_id
        payload = _get(self.store, f"{AUDIT_EVENTS_PATH}/{event_id}")
        self.assertEqual(self.events[0].to_dict(), payload)
        for key in ("event_id", "event_type", "source", "authoritative",
                    "identity", "schema_version", "recorded_at"):
            self.assertIn(key, payload)

    def test_detail_route_retains_original_identity(self):
        event_id = self.by_id and next(
            e.event_id for e in self.events if e.event_type == EVENT_COMPARISON
        )
        payload = _get(self.store, f"{AUDIT_EVENTS_PATH}/{event_id}")
        self.assertEqual(event_id, payload["event_id"])
        self.assertEqual(RUN_ID, payload["identity"]["dataset_run_id"])
        self.assertEqual(EXPERIMENT_ID, payload["identity"]["experiment_id"])
        self.assertEqual(SEQUENCE, payload["identity"]["sequence"])

    def test_unknown_event_id_is_a_structured_404(self):
        with self.assertRaises(ApiError) as ctx:
            _get(self.store, f"{AUDIT_EVENTS_PATH}/audit-ffffffffffffffffffffffffffffffff")
        self.assertEqual(404, ctx.exception.status)
        self.assertEqual("audit_event_not_found", ctx.exception.code)
        self.assertIn("error", ctx.exception.payload())

    def test_unknown_run_is_a_structured_404(self):
        with self.assertRaises(ApiError) as ctx:
            _get(self.store, "/api/v1/runs/no-such-run/audit")
        self.assertEqual(404, ctx.exception.status)
        self.assertEqual("audit_run_not_found", ctx.exception.code)

    def test_unknown_audit_route_is_a_404(self):
        with self.assertRaises(ApiError) as ctx:
            _get(self.store, "/api/v1/audit/nope")
        self.assertEqual(404, ctx.exception.status)
        self.assertIn(ctx.exception.code, ("unknown_route", "unknown_resource"))

    def test_bad_filter_is_a_structured_400(self):
        for params in (
            {"authoritative": "maybe"},
            {"sequence": "not-a-number"},
            {"limit": "0"},
            {"offset": "-1"},
            {"window_index": "abc"},
        ):
            with self.subTest(params=params):
                with self.assertRaises(ApiError) as ctx:
                    _get(self.store, AUDIT_EVENTS_PATH, **params)
                self.assertEqual(400, ctx.exception.status)
                self.assertEqual("invalid_query_parameter", ctx.exception.code)

    def test_run_trail_route(self):
        payload = _get(self.store, f"/api/v1/runs/{RUN_ID}/audit", window_index=3)
        self.assertEqual("audit-run-trail", payload["api"])
        self.assertEqual(RUN_ID, payload["run_id"])
        self.assertEqual(1, payload["window_count"])
        window = payload["windows"][0]
        self.assertEqual(3, window["window_index"])
        self.assertEqual(
            ["expected", "observed", "comparison", "ml", "risk", "explanation"],
            window["stage_names"],
        )
        for stage in window["stages"]:
            self.assertTrue(stage["present"])
            self.assertEqual(len(stage["events"]), stage["event_count"])

    def test_run_trail_route_can_filter_to_one_stage(self):
        payload = _get(
            self.store, f"/api/v1/runs/{RUN_ID}/audit",
            window_index=0, event_type=EVENT_OBSERVED_STATE,
        )
        self.assertEqual(1, payload["window_count"])
        self.assertEqual(1, payload["event_count"])
        self.assertEqual(["observed"], payload["windows"][0]["stage_names"])

    def test_is_audit_path_recognises_only_audit_routes(self):
        for path in (
            AUDIT_EVENTS_PATH,
            f"{AUDIT_EVENTS_PATH}/audit-abc",
            AUDIT_RUNS_PATH,
            f"/api/v1/runs/{RUN_ID}/audit",
        ):
            self.assertTrue(is_audit_path(path), path)
        for path in ("/api/v1/health", "/api/v1/metrics", "/api/v1/evidence/x", "/api/health"):
            self.assertFalse(is_audit_path(path), path)

    def test_audit_surface_requires_a_wired_store(self):
        class _Ctx:
            audit_store = None

        with self.assertRaises(ApiError) as ctx:
            handle_v1_audit(_Ctx(), AUDIT_EVENTS_PATH)
        self.assertEqual(503, ctx.exception.status)
        self.assertEqual("audit_unavailable", ctx.exception.code)

    def test_audit_routes_work_through_the_v1_dispatcher(self):
        class _Ctx:
            audit_store = self.store

        content, content_type = handle_v1_get(_Ctx(), AUDIT_EVENTS_PATH, {"limit": 2})
        self.assertEqual("application/json", content_type)
        self.assertEqual(2, content["count"])
        self.assertEqual(264, content["total"])


