class TestAuditStoreIntegrity(_StoreTestCase):
    def test_known_event_id_returns_the_exact_event(self):
        event = self.events[10]
        fetched = self.store.get_event(event.event_id)
        self.assertIsNotNone(fetched)
        self.assertEqual(event.event_id, fetched.event_id)
        self.assertEqual(event.to_dict(), fetched.to_dict())

    def test_unknown_event_id_is_a_miss_not_a_new_record(self):
        self.assertIsNone(self.store.get_event("audit-0000000000000000000000000000"))
        self.assertEqual(len(self.store), 264)

    def test_reading_twice_yields_identical_identity_and_payload(self):
        event = self.events[5]
        first, second = self.store.get_event(event.event_id), self.store.get_event(event.event_id)
        self.assertEqual(first.event_id, second.event_id)
        self.assertEqual(first.to_dict(), second.to_dict())

    def test_no_read_regenerates_or_alters_event_ids(self):
        ids_before = [e.event_id for e in self.store.select()]
        for _ in range(3):
            _get(self.store, AUDIT_EVENTS_PATH, limit=500)
            _get(self.store, f"/api/v1/runs/{RUN_ID}/audit", limit=500)
        self.assertEqual(ids_before, [e.event_id for e in self.store.select()])

    def test_reads_do_not_mutate_recorded_values(self):
        before = [e.to_dict() for e in self.store.select()]
        payload = _get(self.store, AUDIT_EVENTS_PATH, limit=100)
        self.assertTrue(payload["events"])
        event = self.store.select()[0]
        with self.assertRaises(Exception):
            event.source = "tampered"
        with self.assertRaises(Exception):
            event.recorded_at = "1999-01-01T00:00:00+00:00"
        with self.assertRaises(Exception):
            event.observed_ref = {"esp_seen": True}
        self.assertEqual(before, [e.to_dict() for e in self.store.select()])

    def test_events_are_frozen(self):
        with self.assertRaises(Exception):
            self.events[0].authoritative = not self.events[0].authoritative
        with self.assertRaises(Exception):
            self.events[0].event_id = "audit-forged"

    def test_a_corrupt_journal_is_never_served_partially(self):
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "corrupt.jsonl"
            good = json.loads(HEALTHY_JOURNAL.read_text().splitlines()[0])
            path.write_text(json.dumps(good) + "\n{not json\n", encoding="utf-8")
            # Refused outright: a reader that returned the first (valid) line
            # would present one event as if it were the whole journal.
            with self.assertRaises(AuditJournalUnreadable) as ctx:
                AuditStore(str(path))
            self.assertIn("corrupt audit event", str(ctx.exception))

    def test_a_tampered_journal_is_never_served(self):
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "tampered.jsonl"
            record = json.loads(HEALTHY_JOURNAL.read_text().splitlines()[1])
            self.assertEqual(EVENT_OBSERVED_STATE, record["event_type"])
            self.assertTrue(record["authoritative"])
            record["observed_ref"] = {"esp_seen": True, "ah_seen": True}
            path.write_text(json.dumps(record) + "\n", encoding="utf-8")
            with self.assertRaises(AuditJournalUnreadable) as ctx:
                AuditStore(str(path))
            self.assertIn("modified after it was written", str(ctx.exception))

    def test_a_tampered_authoritative_flag_is_never_served(self):
        """Flipping authoritative on a persisted record is detected."""
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "flipped.jsonl"
            record = json.loads(HEALTHY_JOURNAL.read_text().splitlines()[0])
            record["authoritative"] = True      # expected_state is never authoritative
            path.write_text(json.dumps(record) + "\n", encoding="utf-8")
            with self.assertRaises(AuditJournalUnreadable):
                AuditStore(str(path))

    def test_missing_journal_reports_zero_rather_than_inventing(self):
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            store = AuditStore(str(Path(tmp) / "nope.jsonl"))
            self.assertEqual(0, len(store))
            self.assertFalse(store.available)
            payload = _get(store, AUDIT_EVENTS_PATH)
            self.assertEqual(0, payload["total"])
            self.assertEqual([], payload["events"])

    def test_a_journal_corrupted_after_startup_yields_a_500_not_partial_data(self):
        """The realistic corruption path: valid at boot, damaged on disk later."""
        import os
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "journal.jsonl"
            path.write_text(HEALTHY_JOURNAL.read_text(encoding="utf-8"), encoding="utf-8")
            store = AuditStore(str(path))
            self.assertEqual(264, len(store))

            path.write_text("{broken\n", encoding="utf-8")
            os.utime(path, (0, 0))  # force a detectable change
            with self.assertRaises(ApiError) as ctx:
                _get(store, AUDIT_EVENTS_PATH)
            self.assertEqual(500, ctx.exception.status)
            self.assertEqual("audit_journal_unreadable", ctx.exception.code)
            self.assertNotIn("events", ctx.exception.payload())


