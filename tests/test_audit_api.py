class TestAuditStoreTrail(_StoreTestCase):
    def test_trail_is_ordered_by_stage_then_window(self):
        trail = self.store.run_trail(RUN_ID)
        self.assertIsNotNone(trail)
        self.assertEqual(44, trail["window_count"])
        self.assertEqual(264, trail["event_count"])
        self.assertEqual(
            ["expected", "observed", "comparison", "ml", "risk", "explanation"],
            trail["windows"][0].stage_names(),
        )

    def test_trail_stages_follow_the_canonical_order(self):
        trail = self.store.run_trail(RUN_ID)
        order = list(AUDIT_STAGE_ORDER)
        for window in trail["windows"]:
            positions = [order.index(stage) for stage in window.stage_names()]
            self.assertEqual(sorted(positions), positions,
                             "stages must be emitted in lifecycle order")

    def test_trail_windows_are_in_ascending_window_order(self):
        trail = self.store.run_trail(RUN_ID)
        indexes = [w.window_index for w in trail["windows"]]
        self.assertEqual(sorted(indexes), indexes)
        self.assertEqual(list(range(44)), indexes)

    def test_trail_is_deterministic_across_repeated_reads(self):
        first = self.store.run_trail(RUN_ID)
        second = self.store.run_trail(RUN_ID)
        self.assertEqual(
            [(w.window_index, w.stage_names()) for w in first["windows"]],
            [(w.window_index, w.stage_names()) for w in second["windows"]],
        )

    def test_unknown_run_has_no_trail(self):
        self.assertIsNone(self.store.run_trail("no-such-run"))

    def test_trail_does_not_fabricate_missing_stages(self):
        """A response stage must be absent, not emitted empty."""
        trail = self.store.run_trail(RUN_ID)
        for window in trail["windows"]:
            for stage in window.stage_names():
                self.assertNotIn(stage, ("response", "authorization", "execution"))
        self.assertNotIn("response", trail["stages_present"])
        self.assertNotIn("authorization", trail["stages_present"])
        self.assertNotIn("execution", trail["stages_present"])


