class TestAuditApiIsolation(unittest.TestCase):
    MODULES = (
        "correlation/api/audit_store.py",
        "correlation/api/audit_routes.py",
    )

    def _source(self, name):
        return (REPO_ROOT / name).read_text(encoding="utf-8")

    def test_store_and_routes_do_not_import_execution(self):
        for name in self.MODULES:
            tree = ast.parse(self._source(name))
            for node in ast.walk(tree):
                if isinstance(node, ast.ImportFrom):
                    with self.subTest(module=name, imported=node.module):
                        self.assertNotIn("execution", node.module or "")
                elif isinstance(node, ast.Import):
                    for alias in node.names:
                        with self.subTest(module=name, imported=alias.name):
                            self.assertNotIn("execution", alias.name)

    def test_store_and_routes_do_not_import_a_response_engine(self):
        for name in self.MODULES:
            text = self._source(name)
            for forbidden in ("response.engine", "ResponseEngine", "correlation.response.engine"):
                with self.subTest(module=name, token=forbidden):
                    self.assertNotIn(forbidden, text)

    def test_store_and_routes_never_call_enforcement_or_controllers(self):
        """No handler may reach an action verb, a controller or a journal write.

        Checked on the *call target*, so ordinary in-memory ``list.append`` on
        this module's own stage buckets is not mistaken for a journal write; a
        write is only forbidden when the receiver is the journal/ledger/store.
        """
        write_receivers = ("journal", "ledger", "store", "self.journal")
        action_calls = (
            "execute", "authorize", "approve", "request_approval", "enforce",
            "attach_xdp", "xdp_attach", "detach", "drop", "record_event",
            "extend", "write", "writelines", "truncate",
        )
        for name in self.MODULES:
            tree = ast.parse(self._source(name))
            for node in ast.walk(tree):
                if not isinstance(node, ast.Call):
                    continue
                func = node.func
                if isinstance(func, ast.Attribute):
                    target, receiver = func.attr, func.value
                elif isinstance(func, ast.Name):
                    target, receiver = func.id, None
                else:
                    continue
                receiver_name = ""
                if isinstance(receiver, ast.Name):
                    receiver_name = receiver.id
                elif isinstance(receiver, ast.Attribute):
                    receiver_name = receiver.attr
                if target in ("append", "extend", "write"):
                    for needle in write_receivers:
                        with self.subTest(module=name, call=target, receiver=receiver_name):
                            self.assertNotIn(needle, receiver_name)
                else:
                    with self.subTest(module=name, call=target):
                        self.assertNotIn(target, action_calls)

    def test_store_opens_files_read_only(self):
        source = self._source("correlation/api/audit_store.py")
        self.assertNotIn('"w"', source)
        self.assertNotIn("'w'", source)
        self.assertNotIn("os.remove", source)
        self.assertNotIn("shutil", source)

    def test_reads_do_not_change_observed_or_expected_state(self):
        before = OBSERVATION_JOURNAL.read_bytes()
        store = AuditStore(str(HEALTHY_JOURNAL))
        events = store.select()
        observed_before = [e.observed_ref for e in events if e.observed_ref]
        expected_before = [e.expected_ref for e in events if e.expected_ref]
        _get(store, AUDIT_EVENTS_PATH, limit=100)
        _get(store, f"/api/v1/runs/{RUN_ID}/audit")
        events_after = store.select()
        self.assertEqual(observed_before, [e.observed_ref for e in events_after if e.observed_ref])
        self.assertEqual(expected_before, [e.expected_ref for e in events_after if e.expected_ref])
        self.assertEqual(before, OBSERVATION_JOURNAL.read_bytes())

    def test_no_http_verb_other_than_get_reaches_the_audit_store(self):
        """POST/PUT/DELETE are refused by the transport before any handler."""
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            completed = subprocess.run(
                [sys.executable, "-c",
                 "import sys; sys.path.insert(0, %r);"
                 "from correlation.api.app import DashboardHandler;"
                 "print(hasattr(DashboardHandler, 'do_POST'),"
                 " hasattr(DashboardHandler, 'do_PUT'),"
                 " hasattr(DashboardHandler, 'do_DELETE'))" % str(REPO_ROOT)],
                capture_output=True, text=True, cwd=REPO_ROOT,
            )
            self.assertEqual(0, completed.returncode, completed.stderr)
            self.assertEqual("True True True", completed.stdout.strip())

    def test_store_module_never_appends_to_its_journal(self):
        """The store borrows a journal and only ever reads it.

        Checked structurally: no write call targets the journal, and no file is
        ever opened for writing.
        """
        tree = ast.parse(self._source("correlation/api/audit_store.py"))
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                func = node.func
                receiver = func.value if isinstance(func, ast.Attribute) else None
                receiver_name = getattr(receiver, "attr", getattr(receiver, "id", ""))
                target = getattr(func, "attr", getattr(func, "id", ""))
                if "journal" in str(receiver_name):
                    with self.subTest(call=target, receiver=receiver_name):
                        self.assertNotIn(target, ("append", "extend", "write", "clear"))
            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                with self.subTest(value=node.value):
                    self.assertNotIn(node.value, ("w", "a", "w+", "r+"))
        source = self._source("correlation/api/audit_store.py")
        self.assertIn("self.journal.read()", source)
        for forbidden in ("os.remove", "os.unlink", "shutil", "os.rename"):
            with self.subTest(token=forbidden):
                self.assertNotIn(forbidden, source)


